CREATE SCHEMA IF NOT EXISTS portfolio_web;

CREATE TABLE portfolio_web.categorias
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT categorias_pkey PRIMARY KEY (id),
    CONSTRAINT categorias_nome_key UNIQUE (nome)
);

CREATE TABLE portfolio_web.clientes
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    telefone VARCHAR(20),
    cidade VARCHAR(100),
    uf CHAR(2),
    data_cadastro TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT clientes_pkey PRIMARY KEY (id),
    CONSTRAINT clientes_email_key UNIQUE (email)
);

CREATE TABLE portfolio_web.produtos
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria_id BIGINT NOT NULL,
    sku VARCHAR(40) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(255),
    preco NUMERIC(12, 2) NOT NULL,
    estoque_atual INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT produtos_pkey PRIMARY KEY (id),
    CONSTRAINT produtos_sku_key UNIQUE (sku),
    CONSTRAINT produtos_categoria_id_fkey FOREIGN KEY (categoria_id)
        REFERENCES portfolio_web.categorias (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT produtos_estoque_atual_check CHECK (estoque_atual >= 0),
    CONSTRAINT produtos_preco_check CHECK (preco >= 0)
);

CREATE TABLE portfolio_web.pedidos
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    numero VARCHAR(30) NOT NULL,
    cliente_id BIGINT NOT NULL,
    data_pedido TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    valor_total NUMERIC(12, 2) NOT NULL,
    CONSTRAINT pedidos_pkey PRIMARY KEY (id),
    CONSTRAINT pedidos_numero_key UNIQUE (numero),
    CONSTRAINT pedidos_cliente_id_fkey FOREIGN KEY (cliente_id)
        REFERENCES portfolio_web.clientes (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT pedidos_status_check CHECK (
        status IN ('PENDENTE', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')
    ),
    CONSTRAINT pedidos_valor_total_check CHECK (valor_total >= 0)
);

CREATE TABLE portfolio_web.itens_pedido
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(12, 2) GENERATED ALWAYS AS (
        quantidade::NUMERIC * preco_unitario
    ) STORED,
    CONSTRAINT itens_pedido_pkey PRIMARY KEY (id),
    CONSTRAINT itens_pedido_pedido_id_produto_id_key UNIQUE (pedido_id, produto_id),
    CONSTRAINT itens_pedido_pedido_id_fkey FOREIGN KEY (pedido_id)
        REFERENCES portfolio_web.pedidos (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT itens_pedido_produto_id_fkey FOREIGN KEY (produto_id)
        REFERENCES portfolio_web.produtos (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT itens_pedido_preco_unitario_check CHECK (preco_unitario >= 0),
    CONSTRAINT itens_pedido_quantidade_check CHECK (quantidade > 0)
);

CREATE TABLE portfolio_web.movimentacoes_estoque
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    produto_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    quantidade INTEGER NOT NULL,
    motivo VARCHAR(150) NOT NULL,
    data_movimentacao TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    referencia VARCHAR(40) NOT NULL,
    CONSTRAINT movimentacoes_estoque_pkey PRIMARY KEY (id),
    CONSTRAINT movimentacoes_estoque_referencia_key UNIQUE (referencia),
    CONSTRAINT movimentacoes_estoque_produto_id_fkey FOREIGN KEY (produto_id)
        REFERENCES portfolio_web.produtos (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT movimentacoes_estoque_quantidade_check CHECK (quantidade > 0),
    CONSTRAINT movimentacoes_estoque_tipo_check CHECK (tipo IN ('ENTRADA', 'SAIDA'))
);
